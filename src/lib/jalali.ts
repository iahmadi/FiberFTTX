// Pure offline Jalali (Solar Hijri) calendar converter & Persian formatting utilities

export interface JalaliDate {
  jy: number;
  jm: number;
  jd: number;
}

export interface GregorianDate {
  gy: number;
  gm: number;
  gd: number;
}

